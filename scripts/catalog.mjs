/** Offline local admin: validates catalog JSON and emits reviewable SQL. Never connects to cloud. */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {normalize,validateCatalog} from '../src/lib/validation.ts';
const quote=value=>value==null?'NULL':typeof value==='number'?String(value):`'${String(value).replaceAll("'","''")}'`;
export function validateMediaFiles(seed){
  const publicRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../public');
  for(const r of seed.resources)for(const field of ['icon','image','mobileImage']){
    const filename=r[field];if(!filename)continue;
    const location=path.resolve(publicRoot,filename.slice(1));
    if(!fs.existsSync(location)||!fs.statSync(location).isFile())throw Error(`Missing local ${field} for ${r.id}: ${filename}`);
  }
}
export function catalogSql(input){
  const seed=validateCatalog(input),sql=['-- Generated by scripts/catalog.mjs; review before applying to the selected D1 environment.','-- Apply the whole file with Wrangler D1 execute (local uses an atomic D1 batch).','-- Do not apply individual lines or add BEGIN/COMMIT: D1 manages transactions.'];
  for(const [table,terms] of [['resource_types',seed.types],['categories',seed.categories],['tags',seed.tags]])for(const t of terms)sql.push(`INSERT INTO ${table}(slug,name) VALUES(${quote(t.slug)},${quote(t.name)}) ON CONFLICT(slug) DO UPDATE SET name=excluded.name;`);
  const columns=['id','slug','title','summary','description','type','canonical_url','platforms_json','license','pricing','icon','image','mobile_image','hero_title','media_alt','media_credit','media_kind','status','featured_rank','curated_rank','search_text','created_at','updated_at'];
  for(const r of seed.resources){
    const search=normalize([r.title,r.summary,r.description,...r.platforms,...r.categories.map(s=>seed.categories.find(c=>c.slug===s).name),...r.tags.map(s=>seed.tags.find(t=>t.slug===s).name)].join(' '));
    const values=[r.id,r.slug,r.title,r.summary,r.description,r.type,r.canonicalUrl,JSON.stringify(r.platforms),r.license,r.pricing,r.icon,r.image,r.mobileImage,r.heroTitle,r.mediaAlt,r.mediaCredit,r.mediaKind,r.status,r.featuredRank,r.curatedRank,search,r.createdAt,r.updatedAt];
    sql.push(`INSERT INTO resources(${columns.join(',')}) VALUES(${values.map(quote).join(',')}) ON CONFLICT(id) DO UPDATE SET ${columns.filter(k=>!['id','created_at'].includes(k)).map(k=>`${k}=excluded.${k}`).join(',')};`);
    for(const table of ['resource_categories','resource_tags','sources'])sql.push(`DELETE FROM ${table} WHERE resource_id=${quote(r.id)};`);
    for(const c of r.categories)sql.push(`INSERT INTO resource_categories(resource_id,category_slug) VALUES(${quote(r.id)},${quote(c)});`);
    for(const t of r.tags)sql.push(`INSERT INTO resource_tags(resource_id,tag_slug) VALUES(${quote(r.id)},${quote(t)});`);
    for(const [i,s] of r.sources.entries())sql.push(`INSERT INTO sources(id,resource_id,url,label,fields_json,verified_at) VALUES(${[r.id+'-source-'+(i+1),r.id,s.url,s.label,JSON.stringify(s.fields),s.verifiedAt].map(quote).join(',')});`);
  }
  return sql.join('\n')+'\n';
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    const [command='validate',input='data/catalog.json',output='data/seed.sql']=process.argv.slice(2);
    if(!['validate','generate'].includes(command)){
      const {main}=await import('./editorial/cli.mjs');await main(process.argv.slice(2));
    }else{
    const data=JSON.parse(fs.readFileSync(input,'utf8')),seed=validateCatalog(data);validateMediaFiles(seed);
    if(command==='generate'){fs.writeFileSync(output,catalogSql(data));console.log(`Generated ${output}: ${seed.resources.length} validated resources; no database mutation performed.`);}else console.log(`PASS: ${seed.resources.length} resources, ${seed.types.length} types, evidence and duplicate checks.`);
    }
  }catch(error){console.error(error.message);process.exitCode=1;}
}
